import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const mode = process.argv[2];
const prod = mode === 'production';

// `test` 模式：把测试与其 Markdown fixture 一起打成可用 node 直接运行的单文件。
if (mode === 'test') {
	await esbuild.build({
		entryPoints: ['tests/run.ts'],
		bundle: true,
		platform: 'node',
		format: 'cjs',
		target: 'node18',
		loader: { '.md': 'text' },
		// jsdom 自带资源文件，必须保持外部依赖；obsidian 只有类型定义，用测试存根替代。
		external: ['jsdom'],
		alias: { obsidian: './tests/obsidian-stub.ts' },
		outfile: '.test-build/test.cjs',
		logLevel: 'info',
	});
	process.exit(0);
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
