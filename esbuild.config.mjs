import esbuild from 'esbuild';
import process from 'process';
import { readFile } from 'node:fs/promises';
import { builtinModules } from 'node:module';
import { resolve } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const mode = process.argv[2];
const prod = mode === 'production';

// `test` 模式：把测试与其 Markdown fixture 一起打成可用 node 直接运行的单文件。
if (mode === 'test') {
	// skills/ 下的规范文档也要能当文本读进来，供「规范示例是否真能作答」的自检测试使用。
	// 默认的 .md loader 只覆盖 tests/ 目录里的 fixture，这里显式补上 skills/。
	const skillsMarkdown = {
		name: 'skills-markdown',
		setup(build) {
			build.onResolve({ filter: /(?:^|\/)skills\/.*\.md$/ }, (args) => ({
				path: resolve(args.resolveDir, args.path),
				namespace: 'skills-markdown',
			}));
			build.onLoad({ filter: /.*/, namespace: 'skills-markdown' }, async (args) => ({
				contents: await readFile(args.path, 'utf8'),
				loader: 'text',
			}));
		},
	};

	await esbuild.build({
		entryPoints: ['tests/run.ts'],
		bundle: true,
		platform: 'node',
		format: 'cjs',
		target: 'node18',
		// 样式表也当文本读进来：复盘高亮的可读性只能靠断言声明来守住（见 quiz-styles.test.ts）。
		loader: { '.md': 'text', '.css': 'text' },
		plugins: [skillsMarkdown],
		// jsdom 自带资源文件，必须保持外部依赖；obsidian 只有类型定义，用测试存根替代。
		external: ['jsdom'],
		alias: { obsidian: './tests/obsidian-stub.ts' },
		outfile: '.test-build/test.cjs',
		logLevel: 'info',
	});
	process.exit(0);
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
